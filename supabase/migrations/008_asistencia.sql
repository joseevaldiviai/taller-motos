create table if not exists public.asistencia (
  id          bigint generated by default as identity primary key,
  usuario_id  uuid not null references public.user_profiles(id) on delete cascade,
  ingreso     timestamptz not null default now(),
  salida      timestamptz,
  activo      boolean not null default true,
  creado_en   timestamptz not null default now()
);

create index if not exists idx_asistencia_usuario ON public.asistencia(usuario_id);
create index if not exists idx_asistencia_ingreso  ON public.asistencia(ingreso);

ALTER TABLE public.asistencia ENABLE ROW LEVEL SECURITY;
CREATE POLICY "service_role_all" ON public.asistencia FOR ALL using (true);
